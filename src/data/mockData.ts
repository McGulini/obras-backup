export function buildPhotoBatch(
  prefix: string,
  date: string,
  serviceName: string,
  count: number,
  baseTime: string = '10:00',
  lat: number = -25.5902,
  lng: number = -49.3789,
  uploadedBy: string = 'Elisson'
): DailyLogPhoto[] {
  const result: DailyLogPhoto[] = [];
  const [baseHourStr, baseMinStr] = baseTime.split(':');
  const baseHour = parseInt(baseHourStr || '10', 10);
  const baseMin = parseInt(baseMinStr || '0', 10);

  for (let i = 0; i < count; i++) {
    const minOffset = (i * 12) % 60;
    const hourOffset = Math.floor((baseMin + i * 12) / 60);
    const currHour = (baseHour + hourOffset) % 24;
    const timeFormatted = `${String(currHour).padStart(2, '0')}:${String(minOffset).padStart(2, '0')}`;
    const url = SAMPLE_PHOTO_LIBRARY[i % SAMPLE_PHOTO_LIBRARY.length];

    result.push({
      id: `photo-${prefix}-${i + 1}`,
      url,
      caption: `Registro de execução de ${serviceName} - Foto ${i + 1}`,
      timestamp: `${date}T${timeFormatted}:00Z`,
      service: serviceName,
      latitude: lat + (i * 0.0004 - 0.0002),
      longitude: lng + (i * 0.0003 - 0.0001),
      uploadedBy,
    });
  }
  return result;
}

